"""GitHub Actions: write the build number and the repository into the app (used for updates).
Usage: python tools/stamp.py <build_number> <owner/repo>   -> prints the full version, e.g. 1.0.0.17"""
import re
import sys
from pathlib import Path

py = Path(__file__).resolve().parent.parent / "app/src/main/python/nexusvpn"
build, repo = int(sys.argv[1]), sys.argv[2]
version = re.search(r'APP_VERSION = "([\d.]+)"', (py / "paths.py").read_text("utf-8")).group(1)
(py / "build_info.py").write_text(f'# Generated by tools/stamp.py\nREPO = "{repo}"\nBUILD = {build}\n', "utf-8")
print(f"{version}.{build}")
